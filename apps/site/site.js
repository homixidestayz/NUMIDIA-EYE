async function selectDetection(id, opts) {
  opts = opts || {};
  if (!id) return;
  /* Tapping the selected dot again clears the selection, like the chip and Esc. */
  if (!opts.keep && S.sel.detectionId === id) { clearSelection(); return; }
  selId = id;
  setSelection({ detectionId: id, wilayaCode: S.sel.wilayaCode, incidentId: S.sel.incidentId });
  S.detailPhase = "loading"; S.ai = null; S.aiPhase = "idle";
  renderDetail(); renderAi(); renderChain(); pushDetections();
  /* Auto-load environment for this detection's incident. */
  loadEnvForDetection(id);
  try {
    S.detail = await get(`/detections/${encodeURIComponent(id)}`);
    S.detailPhase = "ready";
    if (map && S.detail) {
      /* Focus the detection's wilaya with fly:false: the tap was on a dot, so
         the dot stays centered instead of being pushed off-screen by the wilaya
         bounds (which used to run right after this flyTo and win). */
      const code = wilayaCodeFromIso(S.detail.wilaya_code);
      if (code != null) focusWilaya(code, { toggle: false, fly: false, keepItem: true });
      map.flyTo({ center: [S.detail.lon, S.detail.lat], zoom: Math.max(map.getZoom(), 7) });
      if (popup) popup.remove();
      popup = new maplibregl.Popup({ closeButton: false, maxWidth: "260px", offset: 12, className: "hpop" })
        .setLngLat([S.detail.lon, S.detail.lat]).setDOMContent(popupNode(S.detail)).addTo(map);
    }
  } catch (err) {
    /* The panel must say what happened. This branch used to leave the slot
       cleared and silent, so a failed fetch was indistinguishable from "no
       selection", and no popup or fly-to ever explained why. */
    S.detail = S.detections.find((d) => d.detection_id === id) || null;
    S.detailPhase = "error";
  }
  renderDetail(); renderAi(); renderChain(); renderSelection();
  if (S.detailPhase === "ready" && S.detail) {
    // The AI tells about every fire: verify automatically on select, no
    // extra tap. The button stays for manual re-verify.
    runVerify();
    // Highlight the incident containing this detection
    try {
      const res = await get(`/detections/${encodeURIComponent(id)}/incident`);
      if (res && res.incident_id) {
        setSelection({ detectionId: id, incidentId: res.incident_id, wilayaCode: S.sel.wilayaCode });
        S.expanded = res.incident_id;
        renderIncidents();
        scrollIncidentIntoView(res.incident_id);
      }
    } catch (e) {
      /* The incident link is optional: the detection itself is already shown. */
    }
    // On phones the detail panel sits below the map; bring it into view
    // so tapping a fire actually shows its information.
    if (window.matchMedia("(max-width: 768px)").matches) {
      const slot = document.getElementById("detail-slot");
      if (slot && slot.firstElementChild) slot.scrollIntoView({ behavior: "smooth", block: "start" });
    }
  }
}

async function runVerify() {
  if (!S.detail || S.aiPhase === "loading") return;
  S.aiPhase = "loading"; renderAi(); renderChain();
  try {
    const res = await fetch(`${API}/detections/${encodeURIComponent(S.detail.detection_id)}/ai`);
    S.ai = await res.json();
  } catch (err) { S.ai = { status: "REQUEST_FAILED", message: err.message }; }
  S.aiPhase = "done";
  renderAi(); renderChain();
}

