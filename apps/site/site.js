function renderIncidents() {
  const list = document.getElementById("inc-list");
  const note = document.getElementById("inc-note");
  /* One filtered set drives the pill and the list together: the pill used to
     count every incident in the country while the list below a focused wilaya
     was empty, which read as "this wilaya has 200 incidents" when it had none. */
  const filtered = selectedIncidents();
  document.getElementById("inc-count").textContent =
    S.incPhase === "ready" ? `${filtered.length} ${T.incN}` : "";
  if (S.incPhase === "loading") { note.textContent = T.loading; list.innerHTML = ""; return; }
  if (S.incPhase === "error") {
    note.className = "note warn"; note.textContent = `${T.incErr} (${esc(S.incErr)})`;
    list.innerHTML = ""; return;
  }
  note.className = "note"; note.textContent = "";
  if (!S.incidents.length) { note.textContent = T.incEmpty; list.innerHTML = ""; return; }
  /* A focused wilaya with no grouped incident is a state worth naming, not an
     empty box and not an error. */
  if (!filtered.length) {
    note.textContent = "";
    list.innerHTML = `<li class="inc-empty"><p class="note">${esc(T.incWilEmpty)}</p>
      <p class="note small">${esc(T.clearSel)}</p></li>`;
    return;
  }

  /* Sort by priority score, highest first (issue #4) */
  const sorted = [...filtered].sort((a, b) => {
    const sa = (a.priority && typeof a.priority.score === "number") ? a.priority.score : 0;
    const sb = (b.priority && typeof b.priority.score === "number") ? b.priority.score : 0;
    return sb - sa;
  });

  list.innerHTML = sorted.map((inc) => {
    const p = inc.priority || {};
    const level = String(p.level || "").toLowerCase();
    const open = S.expanded === inc.id;
    const score = typeof p.score === "number" ? p.score : null;
    const scorePct = score === null ? 0 : Math.max(0, Math.min(100, score * 100));
    const dl = d => (new Date(d)).getTime();
    const ageH = (dl(Date.now()) - dl(inc.last_acq)) / 3600000;
    const ageTxt = UI_LANG === "ar"
      ? (ageH < 1 ? `قبل ${Math.max(1, Math.round(ageH * 60))} دقيقة`
        : ageH < 24 ? `قبل ${ageH.toFixed(1)} ساعة` : `قبل ${Math.round(ageH / 24)} يوم`)
      : (ageH < 1 ? `${Math.max(1, Math.round(ageH * 60))}m ago`
        : ageH < 24 ? `${ageH.toFixed(1)}h ago` : `${Math.round(ageH / 24)}d ago`);
    const wilas = (inc.wilayas || []);
    const liveInc = inc.verification && inc.verification.status === "available";
    const isSel = S.sel.incidentId === inc.id;
    return `<li class="inc ${level}${isSel ? " sel" : ""}" data-inc-id="${esc(inc.id)}">
      <div class="inc-top">
        <span class="prio-badge ${level}">${esc(orUn(level === "critical" ? T.prioCritical : level === "moderate" ? T.prioModerate : level === "low" ? T.prioLow : p.level))}</span>
        <span class="score" title="${esc(T.scoreLbl)}">
          <i style="width:${scorePct}%"></i>
          <b>${score === null ? T.unavailable : score.toFixed(4)}</b>
        </span>
      </div>
      <div class="inc-title">
        <b>${inc.detection_count} ${esc(T.det)}</b>
        ${wilas.length ? `<span class="wilas">${esc(wilas.slice(0, 3).map((w) => apiWilName(w)).join(", "))}${wilas.length > 3 ? ` +${wilas.length - 3}` : ""}</span>` : ""}
      </div>
      <div class="inc-meta">
        <span>${esc(fmt(inc.last_acq))}</span>
        <span class="age">${esc(ageTxt)}</span>
      </div>
      <div class="inc-meta">
        <span>${esc(T.frp)} <b>${esc(inc.max_frp)} MW</b></span>
        ${inc.satellites?.length ? `<span>${esc(inc.satellites.join(" · "))}</span>` : ""}
      </div>
      <div class="inc-persist">${esc(T.when)} ${esc(inc.persistence_hours != null ? `${Number(inc.persistence_hours).toFixed(1)}${UI_LANG === "ar" ? " ساعة" : "h"}` : T.unavailable)}</div>
      <div class="acts">
        <button class="lbtn-s" data-act="expand" data-id="${esc(inc.id)}">${esc(T.prioTitle)}</button>
        <button class="lbtn-s" data-act="report" data-id="${esc(inc.id)}">${esc(T.reportOpen)}</button>
      </div>
      ${open ? `<div class="factors">
        ${(p.factors || []).map((f) => {
          const c = f.normalized * f.weight;
          return `<div class="factor">
            <div class="row"><span>${esc(factorLabel(f.name))}</span><span>${f.weight} → ${c.toFixed(4)}</span></div>
            <div class="bar"><i style="width:${Math.min(100, Math.max(0, c * 100))}%"></i></div>
            <div class="row"><span>${esc(f.evidence)}</span></div></div>`;
        }).join("")}
        <p class="note">${esc(T.prioMissing)}${esc((p.unavailable_factors || []).join(", "))}</p>
        <p class="note strong">${esc(T.prioNotAI)}</p>
        <div class="row"><span>${esc(T.incVerif)}</span>
          <span class="${liveInc ? "ok" : ""}">${esc(orUn((inc.verification || {}).status))}</span></div>
        <p class="note">${esc(T.incVerifNote)}</p>
        <div class="llm-summary" data-inc-id="${esc(inc.id)}">
          <button class="lbtn-s" data-act="llm-summary" data-id="${esc(inc.id)}">AI Briefing</button>
          <div class="llm-summary-text" style="display:none"></div>
        </div>
      </div>` : ""}
      <div class="pid">${esc(inc.id)}</div>
    </li>`;
  }).join("");
}

