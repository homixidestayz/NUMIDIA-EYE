/* Both servers run on this host, so the API is addressed relative to however
   the page itself was reached. Opening the site over the LAN then talks to the
   LAN address instead of the visitor's own 127.0.0.1.
   Precedence: window.NUMIDIA_API_BASE, then ?api= in the URL (a bare number is
   read as a port), then API_PORT on this host. Port 8010 rather than 8000
   because 8000 is taken by another service on this machine. */
const API_PORT = 8010;
function resolveApiBase() {
  if (window.NUMIDIA_API_BASE) return window.NUMIDIA_API_BASE.replace(/\/$/, "");
  const q = new URLSearchParams(location.search).get("api");
  if (q) {
    return (/^\d+$/.test(q)
      ? `${location.protocol}//${location.hostname || "127.0.0.1"}:${q}`
      : q).replace(/\/$/, "");
  }
  return `${location.protocol}//${location.hostname || "127.0.0.1"}:${API_PORT}`;
}
