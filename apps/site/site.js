function currentIncidentIndex() {
  if (!S.expanded) return -1;
  return S.incidents.findIndex((i) => i.id === S.expanded);
}
function stepIncident(delta) {
  if (!S.incidents.length) return;
  const cur = currentIncidentIndex();
  const next = cur < 0 ? (delta > 0 ? 0 : S.incidents.length - 1)
    : (cur + delta + S.incidents.length) % S.incidents.length;
  const inc = S.incidents[next];
  S.expanded = inc.id;
  renderIncidents();
  loadEnv(inc.id);
  const el = document.querySelector(`[data-act="expand"][data-id="${CSS.escape(inc.id)}"]`);
  if (el && el.scrollIntoView) el.scrollIntoView({ block: "nearest", behavior: "smooth" });
}
function stepWilaya(delta) {
  // wilayaCodeAt is the accessor used everywhere else; the boundary features
  // carry shapeISO and were being read as .properties.code, which is undefined
  // on the derived feature set and threw on the first call.
  const ranked = S.wilayas
    .map((w) => {
      const code = wilayaCodeAt(w);
      return code == null ? null : { code, n: wilDetections(code).length };
    })
    .filter((x) => x && x.n > 0)
    .sort((a, b) => b.n - a.n || String(a.code).localeCompare(String(b.code)));
  if (!ranked.length) return;
  const cur = ranked.findIndex((r) => String(r.code) === String(S.wilaya));
  const next = cur < 0 ? 0 : (cur + delta + ranked.length) % ranked.length;
  focusWilaya(ranked[next].code);
}
function installKeyboard() {
  document.addEventListener("keydown", (ev) => {
    const tag = (ev.target && ev.target.tagName) || "";
    if (tag === "INPUT" || tag === "TEXTAREA") return;
    if (ev.key === "Escape") {
      if (S.expanded) { S.expanded = null; renderIncidents(); loadEnv(null); }
      return;
    }
    if (ev.key === "ArrowDown" || ev.key === "j") { ev.preventDefault(); stepIncident(1); }
    else if (ev.key === "ArrowUp" || ev.key === "k") { ev.preventDefault(); stepIncident(-1); }
    else if (ev.key === "ArrowRight") { ev.preventDefault(); stepWilaya(1); }
    else if (ev.key === "ArrowLeft") { ev.preventDefault(); stepWilaya(-1); }
    else if (ev.key === "r") { ev.preventDefault(); loadEnv(S.expanded); }
    else if (ev.key === "?") { ev.preventDefault(); toggleKeys(); }
  });
}

