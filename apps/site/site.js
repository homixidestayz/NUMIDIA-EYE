/* A compass rose where the arrow points the way the wind blows TO.

   Meteorological convention reports the direction wind comes FROM. The downwind
   direction - where a fire spreads and where someone should move away - is the
   opposite bearing. These differ by 180 degrees, and pointing the arrow at the
   FROM bearing would aim an operator straight at the flame front, so the
   conversion is pinned by tests/site.test.js rather than left to inspection. */
function windArrow(bearingDeg) {
  const from = ((Number(bearingDeg) % 360) + 360) % 360;
  const to = (from + 180) % 360;
  return { from, to, rotate: to };
}

function dialSvg(deg, speed) {
  const { to, rotate } = windArrow(deg);
  const calm = !(typeof speed === "number" && speed > 0.05);
  const len = calm ? 6 : 12 + Math.min(20, (speed / 12) * 20);
  return `<svg class="dial" viewBox="0 0 64 64" role="img" aria-label="wind bearing ${Math.round(to)} degrees">
    <circle cx="32" cy="32" r="29" class="dial-ring"/>
    ${[0, 90, 180, 270].map((a) => {
      const r = (a * Math.PI) / 180;
      const x1 = 32 + Math.sin(r) * 24, y1 = 32 - Math.cos(r) * 24;
      const x2 = 32 + Math.sin(r) * 28, y2 = 32 - Math.cos(r) * 28;
      return `<line x1="${x1.toFixed(1)}" y1="${y1.toFixed(1)}" x2="${x2.toFixed(1)}" y2="${y2.toFixed(1)}" class="dial-tick"/>`;
    }).join("")}
    <text x="32" y="11" class="dial-n">N</text>
    <g transform="rotate(${to.toFixed(1)} 32 32)">
      <path d="M32 ${(32 - len).toFixed(1)} L${(32 + 5).toFixed(1)} 34 L32 ${(32 - len + 9).toFixed(1)} L${(32 - 5).toFixed(1)} 34 Z"
        class="${calm ? "dial-arrow calm" : "dial-arrow"}"/>
    </g>
    <circle cx="32" cy="32" r="2.5" class="dial-hub"/>
  </svg>`;
}

/* Band position 0..1 with an explicit low/high reading. These describe measured
   conditions; the label under each bar says which end is which, so a bar can
   never be read backwards as "more of this is better". */
function band(label, value, text, note, invert) {
  if (typeof value !== "number" || !isFinite(value)) {
    return `<div class="band"><div class="band-h"><span>${esc(label)}</span><b>${esc(T.unavailable)}</b></div>
      <div class="band-t"><div class="band-f"></div></div><div class="band-n">${esc(T.unavailable)}</div></div>`;
  }
  const pct = Math.max(0, Math.min(1, invert ? 1 - value : value)) * 100;
  return `<div class="band">
    <div class="band-h"><span>${esc(label)}</span><b>${esc(text)}</b></div>
    <div class="band-t"><div class="band-f" style="width:${pct.toFixed(1)}%"></div></div>
    <div class="band-n">${esc(note)}</div></div>`;
}

