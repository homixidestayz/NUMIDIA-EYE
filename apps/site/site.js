async function loadEnvForDetection(detectionId) {
  /* When a detection is tapped, find its incident and load environment. */
  try {
    const res = await get(`/detections/${encodeURIComponent(detectionId)}/incident`);
    if (res && res.incident_id) {
      await loadEnv(res.incident_id);
    } else {
      S.env = null; S.envPhase = "idle"; S.envId = null; renderEnv();
    }
  } catch (e) {
    S.env = null; S.envPhase = "idle"; S.envId = null; renderEnv();
  }
}

async function loadEnv(incidentId) {
  if (!incidentId) {
    S.env = null; S.envPhase = "idle"; S.envId = null; renderEnv(); return;
  }
  if (S.envId === incidentId && (S.envPhase === "ready" || S.envPhase === "loading")) return;
  S.envId = incidentId; S.envPhase = "loading"; S.envErr = null; renderEnv();
  try {
    S.env = await get(`/incidents/${encodeURIComponent(incidentId)}/environment`);
    S.envPhase = S.env && S.env.status === "AVAILABLE" ? "ready" : "error";
    if (S.envPhase === "error") S.envErr = S.env && S.env.reason;
  } catch (err) {
    S.env = null; S.envPhase = "error"; S.envErr = String(err.message || err);
  }
  renderEnv();
}

