/* The API reports an incident's wilayas as NAMES - the worker groups detections
   by wilaya_name - while everything in this UI (map layer, rail, URL) holds a
   wilaya CODE. Matching "Oran" against "31" dropped every incident of a focused
   wilaya while the pill kept counting all 200. The name -> code index below is
   built once from the bundled boundaries, and every wilaya-scoped count goes
   through the same predicate. */
function buildWilayaNameIndex(wilayas) {
  const idx = {};
  for (const w of wilayas || []) {
    if (!w || w.code === null || w.code === undefined) continue;
    const code = String(w.code);
    for (const n of [w.name, w.nameAr]) {
      if (!n) continue;
      const key = String(n).trim().toLowerCase();
      if (key && idx[key] == null) idx[key] = code;
    }
  }
  return idx;
}
function wilayaCodeForName(name, index) {
  if (name === null || name === undefined) return null;
  const key = String(name).trim().toLowerCase();
  return (index && index[key]) || null;
}
function incidentMatchesWilaya(inc, code, index) {
  if (!code) return true;
  const c = String(code);
  return ((inc && inc.wilayas) || []).some((w) => wilayaCodeForName(w, index) === c);
}
