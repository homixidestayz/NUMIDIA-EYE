/* opts.toggle (default true): a second tap on the same wilaya clears it.
   opts.fly (default true): frame the wilaya. Selection paths pass fly:false so
   their own fly-to is not overwritten by the wilaya bounds - a dot the user
   tapped used to drift off-center because both fought over the camera.
   opts.keepItem (default false): keep the selected incident/detection. Only
   selection paths pass true - a user tapping a wilaya means to leave the
   incident they were looking at. */
function focusWilaya(code, opts) {
  opts = opts || {};
  const toggle = opts.toggle !== false;
  const fly = opts.fly !== false;
  const keepItem = opts.keepItem === true;
  const same = S.wilaya !== null && String(S.wilaya) === String(code);
  const nextCode = toggle && same ? null : (code === null || code === undefined ? null : String(code));
  setSelection({
    wilayaCode: nextCode,
    incidentId: keepItem ? S.sel.incidentId : null,
    detectionId: keepItem ? S.sel.detectionId : null,
  });
  const url = new URL(location.href);
  if (S.wilaya) url.searchParams.set("wilaya", S.wilaya); else url.searchParams.delete("wilaya");
  history.replaceState(null, "", url);
  if (keepItem) {
    S.expanded = S.sel.incidentId || null;
  } else {
    S.expanded = null; selId = null;
    S.detail = null; S.detailPhase = "idle"; S.ai = null; S.aiPhase = "idle";
    if (popup) { popup.remove(); popup = null; }
    renderDetail(); renderAi();
  }
  const w = nextCode ? S.wilayaByCode[nextCode] : null;
  if (w && fly) {
    const ring = exteriorRing(w.geometry);
    if (ring) {
    let wst = 180, s = 90, e = -180, n = -90;
    for (const [lon, lat] of ring) {
      if (lon < wst) wst = lon; if (lon > e) e = lon;
      if (lat < s) s = lat; if (lat > n) n = lat;
    }
    map.fitBounds([[wst, s], [e, n]], { padding: 60, maxZoom: 8, duration: 700 });
    }
  } else if (!nextCode && fly && map && S.wilayas.length) {
    /* Second tap on the same wilaya: zoom back out to the whole country,
       so nobody has to spam the zoom-out button. */
    map.fitBounds(wilayaBounds(), { padding: FIT.padding, maxZoom: FIT.maxZoom, duration: 700 });
  }
  pushWilayas(); pushDetections(); syncAllLabels();
  renderWilaya(); renderStats(); renderChain(); renderIncidents(); renderSelection();
}

/* ---------------------------------------------------------------- text labels
 * The blank style has no glyphs endpoint, so map symbol layers cannot draw
 * text. Both the cluster counts and the wilaya names are therefore rendered as
 * plain DOM markers built here - no glyph fetch, no external dependency, and
 * the type stays crisp at any zoom.
 *
 * Marker elements are attached by MapLibre itself via .addTo(map); nothing here
 * may reparent the map container or the canvas stops painting.
 */
let clusterMarkers = new Map();   // cluster_id -> marker
let wilayaMarkers = new Map();    // code -> marker

/* Exterior ring of a wilaya, handling both Polygon and MultiPolygon.
   GeoJSON nests these differently: a Polygon's coordinates[0] IS the exterior
   ring, while a MultiPolygon's coordinates[0] is a whole polygon (a list of
   rings). Reading coordinates[0] as a ring unconditionally yields NaN for a
   MultiPolygon - which is what Alger is - and MapLibre then throws
   "Invalid LngLat object: (NaN, NaN)", aborting marker creation partway. */
function exteriorRing(geometry) {
  if (!geometry) return null;
  const coords = geometry.coordinates;
  if (!coords || !coords.length) return null;
  if (geometry.type === "MultiPolygon") {
    // Largest polygon by vertex count: the label belongs on the main landmass,
    // not on an outlying island fragment.
    let best = null;
    for (const poly of coords) {
      if (!poly || !poly.length) continue;
      const ring = poly[0];
      if (ring && (!best || ring.length > best.length)) best = ring;
    }
    return best;
  }
  return coords[0];
}

function wilayaAnchor(w) {
  // Area-weighted centroid of the exterior ring: a label sits inside the
  // wilaya rather than on its bounding box, which matters for the long
  // southern and coastal shapes.
  const ring = exteriorRing(w.geometry);
  if (!ring || ring.length < 2) return null;
  let a = 0, cx = 0, cy = 0;
  for (let i = 0, n = ring.length - 1; i < n; i++) {
    const [x0, y0] = ring[i], [x1, y1] = ring[i + 1];
    const f = x0 * y1 - x1 * y0;
    a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f;
  }
  if (Math.abs(a) < 1e-12) return [ring[0][0], ring[0][1]];
  a *= 3;
  return [cx / a, cy / a];
}

function buildWilayaMarkers() {
  for (const [, m] of wilayaMarkers) m.remove();
  wilayaMarkers = new Map();
  for (const w of S.wilayas) {
    const anchor = wilayaAnchor(w);
    // Skip rather than throw: a single unanchorable wilaya must not abort the
    // loop and leave the map with a partial label set, which is exactly what
    // happened when the MultiPolygon centroid returned NaN.
    if (!anchor) continue;
    const el = document.createElement("div");
    el.className = "wlabel";
    el.textContent = wilDisplayName(w);
    const mk = new maplibregl.Marker({ element: el, anchor: "center" })
      .setLngLat(anchor).addTo(map);
    wilayaMarkers.set(String(w.code), mk);
  }
  syncWilayaLabels();
}

/* Every wilaya is labeled at every zoom. The previous build hid names below
   zoom 4.0 and all-but-one while a wilaya was focused, which meant a country-wide
   view showed a handful of names and the other 65 existed only as outlines.

   69 labels at country zoom will collide - northern Algeria packs ~20 wilayas
   into a small area - so names are culled greedily by importance rather than by
   position. Wilayas carrying detections win over empty ones, and the focused one
   always wins, because those are the ones a reader is looking for. "All names"
   overrides the cull and draws every label regardless. */
function labelImportance(w) {
  if (String(w.code) === String(S.wilaya)) return 1e9;
  return wilDetections(w.code).length;
}

function syncWilayaLabels() {
  if (!map || !wilayaMarkers.size) return;
  const focused = S.wilaya;

  const ordered = S.wilayas
    .map((w) => ({ w, mk: wilayaMarkers.get(String(w.code)) }))
    .filter((x) => x.mk)
    .sort((a, b) => labelImportance(b.w) - labelImportance(a.w));

  const placed = [];
  const boxes = [];
  for (const { w, mk } of ordered) {
    const el = mk.getElement();
    const on = String(w.code) === String(focused);
    el.classList.toggle("is-on", on);
    if (!S.showNames || (focused && !on)) { el.style.display = "none"; continue; }

    el.style.display = "";
    if (S.forceAllNames) continue;

    // Measure after display, then keep the label only if it clears everything
    // already placed. getBoundingClientRect reflects the live DOM position.
    const r = el.getBoundingClientRect();
    if (!r.width) continue;
    const hit = boxes.some((b) =>
      r.left < b.right + 2 && r.right > b.left - 2 &&
      r.top < b.bottom + 1 && r.bottom > b.top - 1);
    if (hit) { el.style.display = "none"; continue; }
    boxes.push({ left: r.left, right: r.right, top: r.top, bottom: r.bottom });
    placed.push(w);
  }
  S.labelsShown = placed.length;
  const cnt = document.getElementById("name-count");
  if (cnt) {
    cnt.textContent = S.showNames
      ? (S.forceAllNames ? `${S.wilayas.length} ${UI_LANG === "ar" ? "اسمًا" : "names"}` : `${placed.length}/${S.wilayas.length} ${UI_LANG === "ar" ? "اسمًا" : "names"}`)
      : "";
  }
}

function syncClusterLabels() {
  if (!map || !map.getSource("detections")) return;
  const feats = map.querySourceFeatures("detections", { filter: ["has", "point_count"] });
  const seen = new Set();
  for (const f of feats) {
    const id = f.properties.cluster_id;
    const key = String(id);
    seen.add(key);
    let mk = clusterMarkers.get(key);
    if (!mk) {
      const el = document.createElement("div");
      el.className = "clabel";
      mk = new maplibregl.Marker({ element: el, anchor: "center" }).setLngLat(f.geometry.coordinates).addTo(map);
      clusterMarkers.set(key, mk);
    } else {
      mk.setLngLat(f.geometry.coordinates);
    }
    mk.getElement().textContent = f.properties.point_count_abbreviated;
  }
  for (const [key, mk] of clusterMarkers) {
    if (!seen.has(key)) { mk.remove(); clusterMarkers.delete(key); }
  }
}

function syncAllLabels() {
  syncWilayaLabels();
  syncClusterLabels();
}

