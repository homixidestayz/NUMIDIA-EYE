/* The display layer identifies a wilaya by ISO code ("DZ-58"), while every
   panel, filter and API call wants the bare number ("58"). Deriving it in one
   place stops each consumer from inventing its own parsing — the mistake that
   left `w.code` undefined and broke keyboard navigation on first use. */
function wilayaCodeFromIso(v) {
  if (v === null || v === undefined) return null;
  const s = String(v);
  const m = s.match(/(\d+)\s*$/);
  if (m) return m[1];
  return /^\d+$/.test(s) ? s : null;
}
function wilayaCodeAt(w) {
  if (!w) return null;
  if (w.code !== null && w.code !== undefined) return w.code;
  return wilayaCodeFromIso(w.iso || (w.properties && w.properties.shapeISO));
}

function wilayaBounds() {
  // Fit to the bundled boundaries, not a hand-tuned constant.
  let w = 180, s = 90, e = -180, n = -90;
  for (const f of S.wilayas) {
    const ring = f.geometry.coordinates[0];
    for (const [lon, lat] of ring) {
      if (lon < w) w = lon; if (lon > e) e = lon;
      if (lat < s) s = lat; if (lat > n) n = lat;
    }
  }
  return [[w, s], [e, n]];
}

/* Fire Radiative Power mapped to a radius, because a 5 MW pixel and a 500 MW
   one are not the same thing and a fixed dot hides that.
   Anchored to real magnitude bands rather than a log curve we did not fit:
   <10 MW sub-threshold, 10-100 small, 100-500 large, >500 extreme. */
function frpRadius(frp) {
  if (typeof frp !== "number" || !isFinite(frp) || frp < 0) return 4;
  if (frp < 10) return 4;
  if (frp < 100) return 6;
  if (frp < 500) return 9;
  return 13;
}

function frpColor(frp) {
  if (typeof frp !== "number" || !isFinite(frp)) return "#86998f";
  if (frp < 10) return "#d9a441";
  if (frp < 100) return "#e08b3d";
  if (frp < 500) return "#e5484d";
  return "#ff6b6b";
}

